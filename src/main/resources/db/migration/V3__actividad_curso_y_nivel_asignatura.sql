-- ============================================================
-- MPAZ PRO 6 - V3: actividad por curso y nivel en asignatura
--
-- Decisiones de negocio aplicadas:
--   1. Una asignatura pertenece a un nivel (la disciplina se repite por
--      nivel: "Matematica 6 Basico" y "Matematica 1 Basico" son filas
--      distintas). La unidad hereda el nivel a traves de su asignatura.
--   2. La actividad deja de tener fechas, habilitacion y limite de intentos:
--      pasa a ser una plantilla reutilizable. La configuracion por curso vive
--      en actividad_curso (ventana, habilitada, visible y max_intentos).
--   3. El intento se registra contra la asignacion actividad-curso, no contra
--      la actividad. Asi el limite de intentos y los resultados quedan
--      acotados al curso.
--
-- V1 y V2 ya estan aplicadas: no se editan. Esta es la migracion incremental.
-- ============================================================

-- ============================================================
-- 1) ASIGNATURA -> NIVEL (1:N obligatoria)
-- ============================================================

ALTER TABLE asignatura ADD COLUMN nivel_id bigint;

-- Si ya hubiera asignaturas, el nivel no se puede inferir: se exige
-- asignarlo manualmente antes de aplicar esta migracion.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM asignatura) THEN
        RAISE EXCEPTION 'V3: asignatura tiene filas; asigne asignatura.nivel_id antes de aplicar esta migracion';
    END IF;
END
$$;

ALTER TABLE asignatura ALTER COLUMN nivel_id SET NOT NULL;

ALTER TABLE asignatura
    ADD CONSTRAINT asignatura_nivel_fk
    FOREIGN KEY (nivel_id) REFERENCES nivel (nivel_id);

-- El nombre deja de ser unico global: ahora es unico dentro de cada nivel.
ALTER TABLE asignatura DROP CONSTRAINT unique_asignatura_nombre;

ALTER TABLE asignatura
    ADD CONSTRAINT asignatura__un UNIQUE (nivel_id, nombre);

CREATE INDEX idx_asignatura_nivel
    ON asignatura (nivel_id);

-- ============================================================
-- 2) ACTIVIDAD_CURSO (N:M con configuracion propia)
-- ============================================================

CREATE TABLE actividad_curso (
    actividad_curso_id bigint GENERATED BY DEFAULT AS IDENTITY,
    actividad_id       bigint NOT NULL,
    curso_id           bigint NOT NULL,
    fecha_inicio       timestamptz,
    fecha_fin          timestamptz,
    habilitada         boolean NOT NULL DEFAULT false,
    visible            boolean NOT NULL DEFAULT false,
    max_intentos       integer,
    CONSTRAINT actividad_curso_pk PRIMARY KEY (actividad_curso_id),
    CONSTRAINT actividad_curso__un UNIQUE (actividad_id, curso_id),
    CONSTRAINT actividad_curso_fechas_ck
        CHECK (fecha_fin IS NULL OR fecha_inicio IS NULL OR fecha_fin > fecha_inicio),
    CONSTRAINT actividad_curso_intentos_ck
        CHECK (max_intentos IS NULL OR max_intentos > 0),
    CONSTRAINT actividad_curso_actividad_fk
        FOREIGN KEY (actividad_id) REFERENCES actividad (actividad_id),
    CONSTRAINT actividad_curso_curso_fk
        FOREIGN KEY (curso_id) REFERENCES curso (curso_id)
);

CREATE INDEX idx_actividad_curso_curso
    ON actividad_curso (curso_id, visible, habilitada, fecha_inicio);

-- Conservar la configuracion vigente: una asignacion por cada curso que
-- imparte la asignatura de la actividad. Antes "visible" no existia; se
-- hereda el valor de la antigua actividad.habilitada.
INSERT INTO actividad_curso (
    actividad_id, curso_id, fecha_inicio, fecha_fin,
    habilitada, visible, max_intentos
)
SELECT a.actividad_id, ac.curso_id, a.fecha_inicio, a.fecha_termino,
       a.habilitada, a.habilitada, a.max_intentos
FROM actividad a
JOIN contenido c ON c.contenido_id = a.contenido_id
JOIN unidad u ON u.unidad_id = c.unidad_id
JOIN asignatura_curso ac ON ac.asignatura_id = u.asignatura_id;

-- La actividad queda como plantilla pura.
ALTER TABLE actividad DROP COLUMN fecha_inicio;
ALTER TABLE actividad DROP COLUMN fecha_termino;
ALTER TABLE actividad DROP COLUMN habilitada;
ALTER TABLE actividad DROP COLUMN max_intentos;

-- ============================================================
-- 3) INTENTO -> ACTIVIDAD_CURSO (1:N obligatoria)
-- ============================================================

ALTER TABLE intento ADD COLUMN actividad_curso_id bigint;

-- El backfill solo es posible si el alumno esta inscrito en un unico curso
-- con la actividad asignada. Si hay huerfanos o ambiguedades, se detiene la
-- migracion para resolverlos manualmente.
DO $$
DECLARE
    sin_asignacion bigint;
    ambiguos       bigint;
BEGIN
    SELECT count(*) INTO sin_asignacion
    FROM intento i
    WHERE NOT EXISTS (
        SELECT 1
        FROM actividad_curso ac
        JOIN usuario_curso uc ON uc.curso_id = ac.curso_id
        WHERE ac.actividad_id = i.actividad_id
          AND uc.usuario_id = i.usuario_id
    );

    SELECT count(*) INTO ambiguos
    FROM (
        SELECT i.intento_id
        FROM intento i
        JOIN actividad_curso ac ON ac.actividad_id = i.actividad_id
        JOIN usuario_curso uc
          ON uc.curso_id = ac.curso_id
         AND uc.usuario_id = i.usuario_id
        GROUP BY i.intento_id
        HAVING count(*) > 1
    ) repetidos;

    IF sin_asignacion > 0 OR ambiguos > 0 THEN
        RAISE EXCEPTION 'V3: no se puede derivar intento.actividad_curso_id (sin asignacion=%, ambiguos=%)', sin_asignacion, ambiguos;
    END IF;
END
$$;

UPDATE intento i
SET actividad_curso_id = ac.actividad_curso_id
FROM actividad_curso ac
JOIN usuario_curso uc ON uc.curso_id = ac.curso_id
WHERE ac.actividad_id = i.actividad_id
  AND uc.usuario_id = i.usuario_id;

ALTER TABLE intento ALTER COLUMN actividad_curso_id SET NOT NULL;

ALTER TABLE intento
    ADD CONSTRAINT intento_actividad_curso_fk
    FOREIGN KEY (actividad_curso_id)
    REFERENCES actividad_curso (actividad_curso_id);

ALTER TABLE intento DROP CONSTRAINT intento_actividad_fk;

ALTER TABLE intento DROP COLUMN actividad_id;

CREATE INDEX idx_intento_actividad_curso_usuario
    ON intento (actividad_curso_id, usuario_id);
