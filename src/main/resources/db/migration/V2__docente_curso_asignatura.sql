-- =====================================================================
-- V2: docencia por curso y asignatura
--
-- La relacion docente-curso-asignatura pasa a ser una entidad propia.
-- La asignacion deja de guardar docente_id: el docente se deriva de
-- (curso, asignatura de la unidad).
--
-- El backfill conserva las docencias que se podian inferir de las
-- asignaciones existentes. Si hay dos docentes para el mismo curso y
-- asignatura, la migracion falla (la regla de negocio lo prohibe).
-- =====================================================================

CREATE TABLE docente_curso_asignatura (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    docente_id    bigint NOT NULL,
    curso_id      bigint NOT NULL,
    asignatura_id bigint NOT NULL,
    CONSTRAINT uk_docencia_curso_asignatura UNIQUE (curso_id, asignatura_id),
    CONSTRAINT fk_docencia_docente
        FOREIGN KEY (docente_id) REFERENCES usuario (id),
    CONSTRAINT fk_docencia_curso
        FOREIGN KEY (curso_id) REFERENCES curso (id),
    CONSTRAINT fk_docencia_asignatura
        FOREIGN KEY (asignatura_id) REFERENCES asignatura (id)
);

CREATE INDEX ix_docencia_docente ON docente_curso_asignatura (docente_id);
CREATE INDEX ix_docencia_curso ON docente_curso_asignatura (curso_id);
CREATE INDEX ix_docencia_asignatura ON docente_curso_asignatura (asignatura_id);

-- Backfill desde las asignaciones historicas.
INSERT INTO docente_curso_asignatura (docente_id, curso_id, asignatura_id)
SELECT DISTINCT a.docente_id, a.curso_id, u.asignatura_id
FROM asignacion a
JOIN unidad u ON u.id = a.unidad_id;

ALTER TABLE asignacion DROP COLUMN docente_id;
