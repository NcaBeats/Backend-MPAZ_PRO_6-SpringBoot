-- ============================================================
-- MPAZ PRO 6 - V2: OA multi-unidad, contenido por unidad e informe
--
-- Decisiones de negocio aplicadas:
--   1. Un OA puede pertenecer a varias unidades (curriculum en espiral).
--      Se elimina objetivo_aprendizaje.unidad_id y se crea la tabla puente
--      objetivo_aprendizaje_unidad.
--   2. Un contenido pertenece a una unica unidad y esa unidad es inmutable.
--      Las actividades heredan la unidad a traves de contenido.unidad_id.
--   3. El informe pedagogico se emite en el contexto de una unidad.
--
-- Integridad:
--   - objetivo_aprendizaje_contenido guarda unidad_id y usa FK compuestas
--     para que el contenido y el OA pertenezcan a la misma unidad.
--   - La coherencia entre informe.unidad_id y el OA de cada detalle se
--     valida en la capa de servicio (detalle_informe_pedagogico no duplica
--     la unidad).
--
-- V1 ya esta aplicada: no se edita. Esta es la migracion incremental.
-- ============================================================

-- ============================================================
-- 1) OBJETIVO_APRENDIZAJE <-> UNIDAD (N:M)
-- ============================================================

CREATE TABLE objetivo_aprendizaje_unidad (
    oa_unidad_id            bigint GENERATED BY DEFAULT AS IDENTITY,
    objetivo_aprendizaje_id bigint NOT NULL,
    unidad_id               bigint NOT NULL,
    CONSTRAINT oa_unidad_pk PRIMARY KEY (oa_unidad_id),
    CONSTRAINT oa_unidad__un UNIQUE (objetivo_aprendizaje_id, unidad_id),
    CONSTRAINT oa_unidad_oa_fk
        FOREIGN KEY (objetivo_aprendizaje_id)
        REFERENCES objetivo_aprendizaje (objetivo_aprendizaje_id),
    CONSTRAINT oa_unidad_unidad_fk
        FOREIGN KEY (unidad_id)
        REFERENCES unidad (unidad_id)
);

-- Conservar la asignacion 1:N existente antes de eliminar la columna.
INSERT INTO objetivo_aprendizaje_unidad (objetivo_aprendizaje_id, unidad_id)
SELECT objetivo_aprendizaje_id, unidad_id
FROM objetivo_aprendizaje;

ALTER TABLE objetivo_aprendizaje DROP COLUMN unidad_id;

CREATE INDEX idx_oa_unidad_unidad
    ON objetivo_aprendizaje_unidad (unidad_id);

-- ============================================================
-- 2) CONTENIDO -> UNIDAD (1:N obligatoria)
-- ============================================================

ALTER TABLE contenido ADD COLUMN unidad_id bigint;

-- Si ya hubiera contenidos, la unidad no se puede inferir: se exige
-- asignarla manualmente antes de aplicar esta migracion.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM contenido) THEN
        RAISE EXCEPTION 'V2: contenido tiene filas; asigne contenido.unidad_id antes de aplicar esta migracion';
    END IF;
END
$$;

ALTER TABLE contenido ALTER COLUMN unidad_id SET NOT NULL;

ALTER TABLE contenido
    ADD CONSTRAINT contenido_unidad_fk
    FOREIGN KEY (unidad_id) REFERENCES unidad (unidad_id);

-- Necesario para las FK compuestas del punto 3.
ALTER TABLE contenido
    ADD CONSTRAINT contenido__un UNIQUE (contenido_id, unidad_id);

CREATE INDEX idx_contenido_unidad
    ON contenido (unidad_id);

-- ============================================================
-- 3) OBJETIVO_APRENDIZAJE_CONTENIDO: contenido y OA en la misma unidad
-- ============================================================

ALTER TABLE objetivo_aprendizaje_contenido ADD COLUMN unidad_id bigint;

UPDATE objetivo_aprendizaje_contenido oc
SET unidad_id = c.unidad_id
FROM contenido c
WHERE c.contenido_id = oc.contenido_id;

ALTER TABLE objetivo_aprendizaje_contenido
    ALTER COLUMN unidad_id SET NOT NULL;

-- Reemplazar las FK simples por las compuestas.
ALTER TABLE objetivo_aprendizaje_contenido
    DROP CONSTRAINT oa_cont_contenido_fk;

ALTER TABLE objetivo_aprendizaje_contenido
    DROP CONSTRAINT oa_cont_objetivo_fk;

ALTER TABLE objetivo_aprendizaje_contenido
    ADD CONSTRAINT oa_cont_contenido_unidad_fk
    FOREIGN KEY (contenido_id, unidad_id)
    REFERENCES contenido (contenido_id, unidad_id);

ALTER TABLE objetivo_aprendizaje_contenido
    ADD CONSTRAINT oa_cont_oa_unidad_fk
    FOREIGN KEY (objetivo_aprendizaje_id, unidad_id)
    REFERENCES objetivo_aprendizaje_unidad (objetivo_aprendizaje_id, unidad_id);

CREATE INDEX idx_oa_cont_unidad
    ON objetivo_aprendizaje_contenido (unidad_id);

-- ============================================================
-- 4) INFORME_PEDAGOGICO -> UNIDAD (1:N obligatoria)
-- ============================================================

ALTER TABLE informe_pedagogico ADD COLUMN unidad_id bigint;

-- Si ya hubiera informes, la unidad no se puede inferir: se exige
-- asignarla manualmente antes de aplicar esta migracion.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM informe_pedagogico) THEN
        RAISE EXCEPTION 'V2: informe_pedagogico tiene filas; asigne informe_pedagogico.unidad_id antes de aplicar esta migracion';
    END IF;
END
$$;

ALTER TABLE informe_pedagogico ALTER COLUMN unidad_id SET NOT NULL;

ALTER TABLE informe_pedagogico
    ADD CONSTRAINT informe_pedagogico_unidad_fk
    FOREIGN KEY (unidad_id) REFERENCES unidad (unidad_id);

CREATE INDEX idx_informe_pedagogico_usuario_unidad
    ON informe_pedagogico (usuario_id, unidad_id);

-- ============================================================
-- 5) CONTENIDO.UNIDAD_ID INMUTABLE
-- ============================================================

CREATE OR REPLACE FUNCTION fn_contenido_unidad_inmutable()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.unidad_id IS DISTINCT FROM OLD.unidad_id THEN
        RAISE EXCEPTION 'contenido.unidad_id es inmutable (contenido_id=%)', OLD.contenido_id
            USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_contenido_unidad_inmutable
    BEFORE UPDATE OF unidad_id ON contenido
    FOR EACH ROW
    EXECUTE FUNCTION fn_contenido_unidad_inmutable();
