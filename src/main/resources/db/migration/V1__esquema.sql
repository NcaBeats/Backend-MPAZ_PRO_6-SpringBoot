--   1. Solo los estudiantes tienen curso_id  -> ck_usuario_curso_solo_estudiante
--   6. (validado <-> fecha_validacion)      -> ck_informe_validacion
-- Las demas (rol del docente, del UTP, pertenencia de la pregunta a la
-- actividad del intento, OAs del informe dentro de la unidad) las valida
-- el Service; ver seccion 8, items 1, 2, 9 y 11.
